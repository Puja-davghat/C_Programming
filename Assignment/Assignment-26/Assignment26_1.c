#include <stdio.h>

void DisplayASCII()
{
    int iCnt = 0;

    printf("Symbol \tDecimal \tHexadecimal \tOctal ||    Symbol \tDecimal \tHexadecimal \tOctal\n");
    printf("---------------------------------------------------------------------------------------------------\n");

    for (iCnt = 0; iCnt <= 127; iCnt++)
    {
        int c1 = iCnt;
        int c2 = iCnt + 128;
        char ch1 = ((c1 < 32) || (c1 == 127)) ? ' ' : c1;

        printf("%-6c \t%-7d \t%-11X \t%-6o  ||    %-6c \t%-7d \t%-11X \t%-6o\n",
               ch1, c1, c1, c1,
               c2,  c2, c2, c2);
    }
}

int main()
{
    DisplayASCII();
    return 0;
}
